/**
 * The global game servers' names by id, for the Timers tab's automatic region and the shared
 * timers' Discord channels: src/shared/gameServers.ts.
 *
 *   node scripts/fetch-servers.mjs [--server <dir>]
 *
 * From questlog.gg's armory (`armory.getServers`): every server's id, name and region. The ids are
 * the ones the game sends (Kaisinel 1104), and their second digit is the region (1 NA East, 2 NA
 * West, 3 Europe, 4 Latin America, 5 Asia; 0 is Korea and Taiwan, separate clients, left out).
 * With --server, also writes <dir>/game_servers.json for aion2-api (server/aion2-api). Re-run when
 * NC opens servers.
 *
 * Source: questlog.gg's Aion 2 armory, used with credit.
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const APP = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(APP, 'src', 'shared', 'gameServers.ts')
const API = 'https://questlog.gg/aion-2/api/trpc'
const HEADERS = { 'user-agent': 'aion2-drop-tracker (personal pet collection tracker)', accept: 'application/json' }
// questlog's region codes for the global client, by the id's region digit.
const REGIONS = { nae: 1, naw: 2, eu: 3, la: 4, as: 5 }

const res = await fetch(`${API}/armory.getServers?input=${encodeURIComponent(JSON.stringify({ language: 'en' }))}`, {
  headers: HEADERS,
})
if (!res.ok) throw new Error(`armory.getServers: HTTP ${res.status}`)
const all = (await res.json()).result.data
const servers = all
  .filter((s) => s.region in REGIONS)
  .map((s) => ({ id: s.serverId, name: s.name, region: s.region }))
  .sort((a, b) => a.id - b.id)
for (const s of servers) {
  if (Math.floor(s.id / 100) % 10 !== REGIONS[s.region]) throw new Error(`${s.id} ${s.name}: not region ${s.region}'s digit`)
}
console.log(`${servers.length} global servers of ${all.length}`)

const lines = servers.map((s) => `  ${s.id}: '${s.name.replaceAll("'", "\\'")}',`)
writeFileSync(
  OUT,
  `// Generated by scripts/fetch-servers.mjs from questlog.gg's armory: do not edit by hand.\n` +
    `/** The global game servers' names by id (Kaisinel 1104); the id's second digit is the region. */\n` +
    `export const GAME_SERVERS: Record<number, string> = {\n${lines.join('\n')}\n}\n`,
)
console.log(`wrote ${OUT}`)

const at = process.argv.indexOf('--server')
if (at > 0 && process.argv[at + 1]) {
  const file = join(process.argv[at + 1], 'game_servers.json')
  writeFileSync(file, JSON.stringify(servers, null, 0).replaceAll('},{', '},\n{') + '\n')
  console.log(`wrote ${file}`)
}
